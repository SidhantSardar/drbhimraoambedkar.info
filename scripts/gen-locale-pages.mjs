// Creates the Marathi routes: for every page in src/pages, a thin page under src/pages/mr/ that renders
// the same page (which reads the language from the /mr/ URL). Runs before every build and dev start.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const pages = path.join(path.dirname(fileURLToPath(import.meta.url)), '../src/pages');
const out = path.join(pages, 'mr');
const SKIP = new Set(['404.astro']);
fs.rmSync(out, { recursive: true, force: true });
// The classic-design preview on staging is built in English only, to keep the deploy small.
if (process.env.SKIP_MARATHI === '1') { console.log('Marathi pages: skipped (SKIP_MARATHI=1)'); process.exit(0); }
let n = 0;
(function walk(dir) {
  for (const f of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, f.name);
    if (full === out) continue;
    if (f.isDirectory()) { walk(full); continue; }
    if (!f.name.endsWith('.astro') || SKIP.has(f.name)) continue;
    const rel = path.relative(pages, full);
    const target = path.join(out, rel);
    const src = fs.readFileSync(full, 'utf8');
    let imp = path.relative(path.dirname(target), full).split(path.sep).join('/');
    if (!imp.startsWith('.')) imp = './' + imp;
    const paths = /export\s+(async\s+)?function\s+getStaticPaths/.test(src);
    fs.mkdirSync(path.dirname(target), { recursive: true });
    fs.writeFileSync(target, `---
// Generated by scripts/gen-locale-pages.mjs: the Marathi version of src/pages/${rel.split(path.sep).join('/')}.
import Page${paths ? ', { getStaticPaths as paths }' : ''} from '${imp}';
${paths ? 'export const getStaticPaths = paths;\n' : ''}---
<Page {...Astro.props} />
`);
    n++;
  }
})(pages);
console.log(`Marathi pages: ${n} routes under src/pages/mr/`);
